#ifndef IOS27_PHASE22E_IPC_H
#define IOS27_PHASE22E_IPC_H
#include <stddef.h>
#include <stdint.h>

/* In-process model. NOT a kernel trap, not native XNU MIG or an ABI bridge. */
#define PHASE22E_TASKS 16u
#define PHASE22E_PORTS 128u
#define PHASE22E_QUEUE 32u
#define PHASE22E_WIRE_MAX 512u
#define PHASE22E_OOL_MAX 4096u
#define PHASE22E_DESCRIPTORS 4u
#define PHASE22E_METHODS 8u
#define PHASE22E_COMPLEX UINT32_C(0x80000000)
#define PHASE22E_MOVE_SEND 17u
#define PHASE22E_MOVE_SEND_ONCE 18u
#define PHASE22E_COPY_SEND 19u
#define PHASE22E_MAKE_SEND_ONCE 21u
#define PHASE22E_DESC_PORT 0u
#define PHASE22E_DESC_OOL 1u

typedef struct phase22e_space phase22e_space;
typedef struct {
    uint32_t bits, size, remote_port, local_port, voucher_port;
    int32_t id;
} phase22e_header;
typedef struct {
    uint32_t send, send_once;
    unsigned receive, dead;
} phase22e_rights;
typedef struct {
    uint64_t sends, receives, timeouts, rejected, dead_ports;
    uint64_t messages_pending, ool_bytes_pending, waiters, peak_waiters;
    uint64_t in_flight_transfers, live_ports;
} phase22e_stats;
typedef enum {
    PHASE22E_OK = 0, PHASE22E_BAD = -1, PHASE22E_RIGHT = -2,
    PHASE22E_QUOTA = -3, PHASE22E_TIMEOUT = -4,
    PHASE22E_SIZE = -5, PHASE22E_UNSUPPORTED = -6,
    PHASE22E_CANCELLED = -7, PHASE22E_DEAD = -8
} phase22e_status;

typedef int (*phase22e_handler)(void *ctx, const uint8_t *request,
                                size_t request_size, uint8_t *response,
                                size_t *response_size);
typedef struct {
    int32_t request_id;
    size_t request_size;   /* Exact wire size, including header. */
    size_t response_size;  /* Exact wire size, including header. */
    phase22e_handler invoke;
    void *ctx;
} phase22e_method;

phase22e_space *phase22e_new(void);
void phase22e_free(phase22e_space *space);
int phase22e_port_create(phase22e_space *space, uint32_t task, uint32_t *port);
int phase22e_make_send(phase22e_space *space, uint32_t owner, uint32_t port,
                       uint32_t recipient);
int phase22e_drop_send(phase22e_space *space, uint32_t task, uint32_t port);
int phase22e_destroy(phase22e_space *space, uint32_t task, uint32_t port);
int phase22e_task_die(phase22e_space *space, uint32_t task);
int phase22e_rights_get(phase22e_space *space, uint32_t task, uint32_t port,
                        phase22e_rights *out);
int phase22e_stats_get(phase22e_space *space, phase22e_stats *out);
int phase22e_cancel_waits(phase22e_space *space);

/* All guest offsets are copied from an explicitly bounded byte arena.
 * No guest pointer is ever dereferenced. Send copies OOL bytes atomically.
 * Wire input and OOL output must be distinct from space-private memory.
 * A successful receive returns wire+OOL lengths separately. Short output
 * does not dequeue or partially write either output.
 */
int phase22e_send(phase22e_space *space, uint32_t task,
                  const void *wire, size_t wire_length,
                  const uint8_t *arena, size_t arena_length,
                  uint32_t timeout_ms);
int phase22e_receive(phase22e_space *space, uint32_t task, uint32_t port,
                     void *wire, size_t *wire_length,
                     void *ool, size_t *ool_length, uint32_t timeout_ms);

/* MIG-style typed model dispatch; methods array must remain alive throughout
 * the call. A handler writes its exact response payload and may make nested
 * RPC calls. No autogenerated XNU IDL stubs or native Mach trap assumed. */
/* Registered method tables are copied under the namespace lock. Unregister
 * fails closed while dispatch is active; callers may release handler context
 * only after a successful unregister. Nested RPC never holds this lock. */
int phase22e_service_register(phase22e_space *space, uint32_t task, uint32_t port,
                              const phase22e_method *methods, size_t count);
int phase22e_service_unregister(phase22e_space *space, uint32_t task, uint32_t port);
int phase22e_service_dispatch(phase22e_space *space, uint32_t task, uint32_t port,
                              const void *request, size_t request_length,
                              void *reply, size_t *reply_length);
int phase22e_mig_dispatch(const phase22e_method *methods, size_t count,
                          const void *request, size_t request_length,
                          void *reply, size_t *reply_length);
#endif
